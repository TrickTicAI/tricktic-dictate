//! Native clipboard policy acceptance using a unique named pasteboard only.
//! Never reads, snapshots or replaces the user's general pasteboard. A child
//! process acts as the reader/concurrent copier; AppKit serves lazy data on the
//! parent's main run loop. Does not prove clipboard-manager or sync behavior.
#![allow(dead_code)]
#[cfg(target_os = "macos")]
#[path = "../src/shell/macos_clipboard.rs"]
mod macos_clipboard;

#[cfg(not(target_os = "macos"))]
fn main() {}

#[cfg(target_os = "macos")]
fn main() {
    use objc2_app_kit::NSPasteboard;
    use objc2_foundation::NSString;
    let args: Vec<_> = std::env::args().collect();
    if let [_, operation, name] = args.as_slice() {
        // Child mode cannot address the general or a user-supplied pasteboard.
        assert!(name.starts_with("com.metrix.writer.clipboard-probe."));
        let board = NSPasteboard::pasteboardWithName(&NSString::from_str(name));
        match operation.as_str() {
            "--read" => {
                let text = board
                    .stringForType(&NSString::from_str("public.utf8-plain-text"))
                    .expect("synthetic text");
                print!("{text}");
            }
            "--copy" => {
                macos_clipboard::write_on(&board, "MW-SEC-15 newer copy", false).expect("new copy");
            }
            _ => panic!("unknown probe operation"),
        }
        return;
    }
    assert_eq!(args.len(), 1, "probe accepts no external pasteboard name");
    std::thread::spawn(|| {
        let result = std::panic::catch_unwind(probe);
        std::process::exit(if result.is_ok() { 0 } else { 1 });
    });
    core_foundation::runloop::CFRunLoop::run_current();
}

#[cfg(target_os = "macos")]
fn probe() {
    use macos_clipboard::*;
    use objc2_app_kit::{NSPasteboard, NSPasteboardItem};
    use objc2_foundation::NSString;
    use std::process::Command;
    use std::sync::atomic::Ordering;
    use std::time::{Duration, Instant};

    let name = format!("com.metrix.writer.clipboard-probe.{}", uuid::Uuid::new_v4());
    let board = NSPasteboard::pasteboardWithName(&NSString::from_str(&name));
    let previous: Snapshot = vec![vec![
        (
            "public.utf8-plain-text".into(),
            b"MW-SEC-15 previous".to_vec(),
        ),
        ("public.html".into(), b"<b>previous</b>".to_vec()),
    ]];
    let child = |operation: &str| {
        let mut process = Command::new(std::env::current_exe().unwrap())
            .args([operation, name.as_str()])
            .stdout(std::process::Stdio::piped())
            .spawn()
            .unwrap();
        let deadline = Instant::now() + Duration::from_secs(5);
        while process.try_wait().unwrap().is_none() {
            if Instant::now() >= deadline {
                let _ = process.kill();
                let _ = process.wait();
                panic!("synthetic clipboard child timed out");
            }
            std::thread::sleep(Duration::from_millis(10));
        }
        let output = process.wait_with_output().unwrap();
        assert!(output.status.success(), "synthetic clipboard child failed");
        String::from_utf8(output.stdout).unwrap()
    };
    let check_markers = |private: bool, transient: bool| {
        let items = board.pasteboardItems().expect("published items");
        let item: &NSPasteboardItem = &items.firstObject().expect("published item");
        let types: Vec<_> = item.types().iter().map(|t| t.to_string()).collect();
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            assert_eq!(types.iter().any(|t| t == marker), private, "{marker}");
        }
        assert_eq!(
            types.iter().any(|t| t == "org.nspasteboard.TransientType"),
            transient
        );
    };
    for private in [false, true] {
        for text in [
            "MW-SEC-15 English",
            "MW-SEC-15 שלום",
            "MW-SEC-15 mixed שלום",
        ] {
            assert!(restore_on(&board, &previous, board.changeCount()));
            let taken = snapshot_on(&board).unwrap();
            assert_eq!(taken, previous);
            let generation = write_on(&board, text, private).unwrap();
            check_markers(private, false);
            assert_eq!(child("--read"), text);
            let published = publish_on(&board, text, generation, private).unwrap();
            check_markers(private, private);
            assert_eq!(child("--read"), text);
            let deadline = Instant::now() + Duration::from_secs(2);
            while !published.read.load(Ordering::Acquire) && Instant::now() < deadline {
                std::thread::sleep(Duration::from_millis(10));
            }
            assert!(published.read.load(Ordering::Acquire));
            assert!(restore_on(&board, &taken, published.generation));
            assert_eq!(snapshot_on(&board).unwrap(), previous);

            // An unread lazy item remains pasteable after provider release,
            // with confidentiality retained but no false transient claim.
            let published = publish_on(&board, text, board.changeCount(), private).unwrap();
            assert!(materialize_on(&board, text, published.generation, private));
            drop(published);
            check_markers(private, false);
            assert_eq!(child("--read"), text);

            // The external copy changes the native generation and wins over
            // both restoration and fallback materialization.
            let published = publish_on(&board, text, board.changeCount(), private).unwrap();
            child("--copy");
            assert!(!restore_on(&board, &taken, published.generation));
            assert!(!materialize_on(&board, text, published.generation, private));
            drop(published);
            assert_eq!(child("--read"), "MW-SEC-15 newer copy");
            check_markers(false, false);
        }
        println!("PASS private={private}: native markers, observed read, byte restoration, unread fallback and newer-copy guards in three language cases");
    }
    board.clearContents();
}
