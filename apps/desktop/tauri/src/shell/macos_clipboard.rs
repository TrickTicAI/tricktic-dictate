//! macOS clipboard preservation: the previous pasteboard comes back after a paste
//! is observed, never after elapsed time alone. Pasteboard bytes and dictation
//! stay in memory and are never logged or persisted.
//!
//! macOS names no reader, so observation uses a lazily provided item: AppKit
//! asks Writer for the text the first time any application reads it, on the
//! main thread, and caches the answer for later readers.
use objc2::rc::autoreleasepool;
use objc2::{
    define_class, msg_send, rc::Retained, runtime::ProtocolObject, AllocAnyThread, DefinedClass,
};
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardItemDataProvider, NSPasteboardType,
    NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSObject, NSObjectProtocol, NSString};
use std::sync::{
    atomic::{AtomicBool, Ordering},
    Arc,
};

const MAX_CLIPBOARD: usize = 16 * 1024 * 1024;
const TEXT: &str = "public.utf8-plain-text";

/// Every item on the pasteboard with each type that yields bytes. Types whose
/// data cannot be read, such as file promises, are omitted from the restore.
pub(super) type Snapshot = Vec<Vec<(String, Vec<u8>)>>;

/// A lazily provided dictation on the pasteboard. Dropping it releases the
/// provider, so the caller replaces or loses the item first.
pub(super) struct Published {
    pub generation: isize,
    pub read: Arc<AtomicBool>,
    pub _provider: Option<Box<dyn std::any::Any>>,
}

pub(super) struct ProviderState {
    text: String,
    read: Arc<AtomicBool>,
}

define_class!(
    #[unsafe(super(NSObject))]
    #[name = "MetrixWriterDictationProvider"]
    #[ivars = ProviderState]
    struct Provider;

    unsafe impl NSObjectProtocol for Provider {}

    unsafe impl NSPasteboardItemDataProvider for Provider {
        #[unsafe(method(pasteboard:item:provideDataForType:))]
        fn provide(
            &self,
            _pasteboard: Option<&NSPasteboard>,
            item: &NSPasteboardItem,
            kind: &NSPasteboardType,
        ) {
            let state = self.ivars();
            item.setString_forType(&NSString::from_str(&state.text), kind);
            state.read.store(true, Ordering::Release);
        }
    }
);

impl Provider {
    fn new(text: &str, read: Arc<AtomicBool>) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderState {
            text: text.to_owned(),
            read,
        });
        unsafe { msg_send![super(this), init] }
    }
}

/// The current pasteboard, or `None` when there is nothing to preserve or it
/// is larger than preservation retains. `None` means ordinary delivery.
pub(super) fn snapshot() -> Option<Snapshot> {
    snapshot_on(&NSPasteboard::generalPasteboard())
}

pub(super) fn snapshot_on(board: &NSPasteboard) -> Option<Snapshot> {
    autoreleasepool(|_| {
        let before = board.changeCount();
        let mut total = 0;
        let mut items = Vec::new();
        for item in board.pasteboardItems()?.iter() {
            let mut entries = Vec::new();
            for kind in item.types().iter() {
                let Some(data) = item.dataForType(&kind) else {
                    continue;
                };
                total += data.len();
                if total > MAX_CLIPBOARD {
                    return None;
                }
                entries.push((kind.to_string(), data.to_vec()));
            }
            if !entries.is_empty() {
                items.push(entries);
            }
        }
        (!items.is_empty() && board.changeCount() == before).then_some(items)
    })
}

fn replace(board: &NSPasteboard, items: &[Retained<NSPasteboardItem>]) -> Option<isize> {
    let generation = board.clearContents();
    let objects: Vec<&ProtocolObject<dyn NSPasteboardWriting>> = items
        .iter()
        .map(|item| ProtocolObject::from_ref(&**item))
        .collect();
    // clearContents returns the new count; the write must not advance past it,
    // or another application wrote in between.
    (board.writeObjects(&NSArray::from_slice(&objects)) && board.changeCount() == generation)
        .then_some(generation)
}

/// These are cooperative conventions, not access control or a Universal
/// Clipboard API. Fallback text is confidential but may remain indefinitely.
fn mark_private(item: &NSPasteboardItem, private: bool, transient: bool) -> bool {
    !private
        || [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
        ]
        .into_iter()
        .chain(transient.then_some("org.nspasteboard.TransientType"))
        .all(|kind| item.setData_forType(&NSData::with_bytes(&[]), &NSString::from_str(kind)))
}

/// Explicit Copy passes false; automatic delivery carries its selected policy.
pub(super) fn write(text: &str, private: bool) -> Option<isize> {
    write_on(&NSPasteboard::generalPasteboard(), text, private)
}

pub(super) fn write_on(board: &NSPasteboard, text: &str, private: bool) -> Option<isize> {
    autoreleasepool(|_| {
        let item = NSPasteboardItem::new();
        if !mark_private(&item, private, false)
            || !item.setString_forType(&NSString::from_str(text), &NSString::from_str(TEXT))
        {
            return None;
        }
        replace(board, &[item])
    })
}

/// Replaces Writer's own unchanged publication with a lazily provided copy of
/// the same text. Returns `None`, touching nothing, if anyone copied since.
pub(super) fn publish(text: &str, expected: isize, private: bool) -> Option<Published> {
    publish_on(&NSPasteboard::generalPasteboard(), text, expected, private)
}

pub(super) fn publish_on(
    board: &NSPasteboard,
    text: &str,
    expected: isize,
    private: bool,
) -> Option<Published> {
    autoreleasepool(|_| {
        if board.changeCount() != expected {
            return None;
        }
        let read = Arc::new(AtomicBool::new(false));
        let provider = Provider::new(text, read.clone());
        let item = NSPasteboardItem::new();
        let kinds = NSArray::from_retained_slice(&[NSString::from_str(TEXT)]);
        if !mark_private(&item, private, true)
            || !item.setDataProvider_forTypes(ProtocolObject::from_ref(&*provider), &kinds)
        {
            return None;
        }
        let generation = replace(board, &[item])?;
        Some(Published {
            generation,
            read,
            _provider: Some(Box::new(provider)),
        })
    })
}

/// Puts the dictation back as ordinary text if Writer's lazy item is still
/// current, so a late paste works after the provider is released.
pub(super) fn materialize(text: &str, expected: isize, private: bool) -> bool {
    materialize_on(&NSPasteboard::generalPasteboard(), text, expected, private)
}

pub(super) fn materialize_on(
    board: &NSPasteboard,
    text: &str,
    expected: isize,
    private: bool,
) -> bool {
    autoreleasepool(|_| {
        if board.changeCount() != expected {
            return false;
        }
        let item = NSPasteboardItem::new();
        mark_private(&item, private, false)
            && item.setString_forType(&NSString::from_str(text), &NSString::from_str(TEXT))
            && replace(board, &[item]).is_some()
    })
}

/// Restores the snapshot if Writer's publication is still current. A newer
/// copy by the user or another application always wins.
pub(super) fn restore(previous: &Snapshot, expected: isize) -> bool {
    restore_on(&NSPasteboard::generalPasteboard(), previous, expected)
}

pub(super) fn restore_on(board: &NSPasteboard, previous: &Snapshot, expected: isize) -> bool {
    autoreleasepool(|_| {
        if board.changeCount() != expected {
            return false;
        }
        let items: Vec<_> = previous
            .iter()
            .map(|entries| {
                let item = NSPasteboardItem::new();
                for (kind, bytes) in entries {
                    item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(kind));
                }
                item
            })
            .collect();
        replace(board, &items).is_some()
    })
}
