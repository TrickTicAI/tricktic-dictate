#!/usr/bin/env node
// MW-SEC-21: inspect one public Windows installer and its fully extracted payload.
// Extract with 7-Zip first (it unpacks NSIS installers without running them):
//   7z.exe x -o<payload> <setup.exe>
// This reads files only. It never runs the installer, contacts a feed or signs.
import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { verifySignature } from '../../desktop/signature.mjs';
import { verifyMetadata, SIDECAR, WRITER_APP, DICTATE_APP } from '../../desktop/update-metadata.mjs';
import { assertNoDesktopFixture, assertNoGoogleSignIn, assertGoogleSignIn, assertSupportedDesktopResources } from '../../desktop/security-artifact.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
// Installer-owned files that are not part of the pinned runtime lock.
export const INSTALLER_FILES = new Map([
  ['tricktic-dictate.exe', 'Writer application'],
  ['uninstall.exe', 'NSIS uninstaller generated by the build'],
  ['notices/RUST-NOTICES.txt', 'Rust dependency notices generated by the build'],
  ['runtime-manifest.json', 'staged runtime manifest generated by the build'],
  // Generated by scripts/desktop/notices.mjs (MW-RELEASE-4).
  ['notices/MODELS-NOTICES.txt', 'model notices generated by the build'],
  ['notices/WEB-NOTICES.txt', 'web dependency notices generated by the build'],
  ['notices/index.json', 'notice index generated by the build'],
  ['notices/source/README.txt', 'FFmpeg source offer generated by the build'],
  ['notices/source/ffmpeg-8.0.3.tar.xz', 'FFmpeg corresponding source, pinned in scripts/inference/ffmpeg-source.json'],
  ['$PLUGINSDIR/StartMenu.dll', 'NSIS plugin'],
  ['$PLUGINSDIR/System.dll', 'NSIS plugin'],
  ['$PLUGINSDIR/nsDialogs.dll', 'NSIS plugin'],
  ['$PLUGINSDIR/nsis_tauri_utils.dll', 'Tauri NSIS plugin'],
  ['$PLUGINSDIR/modern-wizard.bmp', 'NSIS wizard image'],
]);
// installer.nsh stages a new version and swaps exactly these names into place
// (MW-SEC-26 W-13/W-14); anything else installed would escape that swap.
export const SWAPPED = new Set(['tricktic-dictate.exe', 'runtime', 'notices', 'runtime-manifest.json']);
// 7-Zip shows the staged items under the installer's output folder.
export const STAGE = '.writer-staged/';
export const installedPath = path => path.startsWith(STAGE) ? path.slice(STAGE.length) : path;
export function unstaged(raw) {
  return raw.filter(path => !path.startsWith(STAGE) && SWAPPED.has(path.split('/')[0]));
}
export function unswapped(paths) {
  return paths.filter(path => !path.startsWith('$PLUGINSDIR/') && path !== 'uninstall.exe' && !SWAPPED.has(path.split('/')[0]));
}
// Build, debug and source leftovers that must never ship.
const DEBUG = /\.(pdb|ilk|map|obj|o|lib|exp|a|cs|csproj|config|env|pem|key|p12|pfx|log)$/i;
// Upstream tools shipped inside runtime packages that Writer never starts.
// They are reported for review; they are not proof of a vulnerability.
const DEV_HELPERS = /(^|\/)(llama-(bench|batched-bench|cli|completion|fit-params|perplexity|quantize)-impl\.dll|ggml-rpc\.dll|rpc-server(\.exe)?)$/i;

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
async function files(dir, base = dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isSymbolicLink()) throw Error(`Symlink in extracted payload: ${relative(base, path)}`);
    if (entry.isDirectory()) out.push(...await files(path, base));
    else if (entry.isFile()) out.push(relative(base, path).replaceAll('\\', '/'));
    else throw Error(`Unsupported payload entry: ${relative(base, path)}`);
  }
  return out.sort();
}

export function classify(paths, lock) {
  const locked = new Map(lock.files.map(file => [file.path, file]));
  const extra = paths.filter(path => !locked.has(path) && !INSTALLER_FILES.has(path));
  const missing = [...locked.keys(), ...INSTALLER_FILES.keys()].filter(path => !paths.includes(path));
  return { extra, missing, debug: paths.filter(path => DEBUG.test(path)), devHelpers: paths.filter(path => DEV_HELPERS.test(path)) };
}

function differingBytes(a, b) {
  if (a.length !== b.length) return null;
  let count = 0;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) count++;
  return count;
}

async function main() {
  const args = Object.fromEntries(process.argv.slice(2).reduce((pairs, arg, index, all) =>
    arg.startsWith('--') ? [...pairs, [arg.slice(2), all[index + 1]]] : pairs, []));
  for (const key of ['installer', 'payload', 'out']) if (!args[key]) throw Error(`--${key} is required`);
  const installer = resolve(args.installer), payload = resolve(args.payload);
  const receipt = JSON.parse(await readFile(`${installer}.receipt.json`, 'utf8'));
  const config = JSON.parse(await readFile(join(ROOT, 'apps/desktop/tauri/tauri.conf.json'), 'utf8'));
  const lock = JSON.parse(await readFile(join(ROOT, 'scripts/desktop/windows-runtime.lock.json'), 'utf8'));
  const bytes = await readFile(installer);
  const checks = [], findings = [];
  const check = (name, ok, detail) => { checks.push({ name, passed: Boolean(ok), ...(detail === undefined ? {} : { detail }) }); };

  check('installer hash matches receipt', sha256(bytes) === receipt.artifact?.sha256 && bytes.length === receipt.artifact?.bytes);
  check('explicit public mode without Authenticode', receipt.releaseType === 'public-windows-without-authenticode'
    && receipt.authenticode === null && receipt.authenticodeOmitted === true);
  check('clean unchanged source', receipt.dirty === false && receipt.sourceChanged === false && /^[0-9a-f]{40}$/.test(receipt.commit ?? ''));
  check('runtime lock matches receipt', sha256(await readFile(join(ROOT, 'scripts/desktop/windows-runtime.lock.json'))) === receipt.runtimeLockSha256);
  const signature = await readFile(`${installer}.sig`, 'utf8');
  check('signature hash matches receipt', sha256(Buffer.from(signature)) === receipt.signature?.sha256);
  try { verifySignature(bytes, signature, config.plugins.updater.pubkey); check('minisign signature verifies with the embedded updater key', true); }
  catch (error) { check('minisign signature verifies with the embedded updater key', false, error.message); }
  let manifest = null;
  // One envelope for installed Metrix Writer copies, one for this identity.
  for (const app of [WRITER_APP, DICTATE_APP]) {
    const name = `signed ${app} release metadata verifies and is fresh`;
    try {
      manifest = verifyMetadata(JSON.parse(await readFile(`${installer}${SIDECAR[app]}`, 'utf8')), bytes,
        receipt.appVersion, 'windows-x86_64', config.plugins.updater.pubkey, undefined, app);
      check(name, true, manifest);
    } catch (error) { check(name, false, error.message); }
  }
  check('product version matches receipt', config.version === receipt.appVersion);

  const raw = await files(payload);
  const paths = raw.map(installedPath).sort();
  const located = new Map(raw.map(path => [installedPath(path), join(payload, path)]));
  const at = path => located.get(path) ?? join(payload, path);
  const found = classify(paths, lock);
  check('no unexpected files beyond the runtime lock and installer files', found.extra.length === 0, found.extra);
  check('no missing locked or installer files', found.missing.length === 0, found.missing);
  check('no debug, source or key files', found.debug.length === 0, found.debug);
  check('every installed item is replaced by the staged swap', unswapped(paths).length === 0 && unstaged(raw).length === 0,
    [...unswapped(paths), ...unstaged(raw)]);
  // MW-SEC-26 W-03/W-04: no unused upstream tools and no embedded WebView2 bootstrapper.
  check('no unused upstream tool or RPC libraries', found.devHelpers.length === 0, found.devHelpers);
  check('no embedded WebView2 bootstrapper', !paths.some(path => /webview2/i.test(path)));
  const mismatched = [];
  for (const file of lock.files) {
    const path = at(file.path);
    try {
      const data = await readFile(path);
      if (sha256(data) !== file.sha256 || data.length !== file.bytes) mismatched.push(file.path);
    } catch { /* reported as missing */ }
  }
  check('every locked runtime file matches its pinned hash and size', mismatched.length === 0, mismatched);
  const key = file => `${file.path}\n${file.bytes}\n${file.sha256}`;
  const shipped = JSON.parse(await readFile(at('runtime-manifest.json'), 'utf8')).map(key).sort();
  const ffmpeg = JSON.parse(await readFile(join(ROOT, 'scripts/inference/ffmpeg-source.json'), 'utf8'));
  const sourcePath = at(`notices/source/ffmpeg-${ffmpeg.version}.tar.xz`);
  const sourceBytes = paths.includes(`notices/source/ffmpeg-${ffmpeg.version}.tar.xz`) ? await readFile(sourcePath) : Buffer.alloc(0);
  check('shipped FFmpeg source matches its signature-verified pin', sourceBytes.length === ffmpeg.bytes && sha256(sourceBytes) === ffmpeg.sha256);
  check('shipped runtime manifest lists exactly the locked files', JSON.stringify(shipped) === JSON.stringify(lock.files.map(key).sort()));
  try { assertSupportedDesktopResources(paths); check('no retired C#/WebView2 entry points', true); }
  catch (error) { check('no retired C#/WebView2 entry points', false, error.message); }
  const exe = at('tricktic-dictate.exe');
  for (const [name, assert] of [['no security-probe fixture code', assertNoDesktopFixture], [receipt.googleSignIn === true ? 'requested Google sign-in code is present' : 'no Google sign-in code', receipt.googleSignIn === true ? assertGoogleSignIn : assertNoGoogleSignIn]]) {
    try { await assert(exe); check(name, true); } catch (error) { check(name, false, error.message); }
  }
  const exeBytes = await readFile(exe);
  // The receipt hashes the build-folder EXE after Tauri restores its bundle-type
  // marker; the shipped EXE carries the NSIS marker (docs/security/windows-signing.md).
  const built = receipt.executable?.sha256 === sha256(exeBytes);
  if (!built) findings.push({ id: 'RECEIPT-EXECUTABLE-HASH', severity: 'low',
    detail: 'Receipt executable hash is the build-folder copy, not the shipped EXE.',
    shipped_sha256: sha256(exeBytes), receipt_sha256: receipt.executable?.sha256, shipped_bytes: exeBytes.length,
    receipt_bytes: receipt.executable?.bytes });

  const result = {
    schema: 1, kind: 'mw-sec-21-installer-inspection', created_at: new Date().toISOString(),
    installer: { name: installer.split('/').pop(), bytes: bytes.length, sha256: sha256(bytes) },
    source_commit: receipt.commit, app_version: receipt.appVersion, release_type: receipt.releaseType,
    metadata: manifest, payload: { files: paths.length, bytes: (await Promise.all(paths.map(path => stat(at(path))))).reduce((sum, s) => sum + s.size, 0),
      shipped_executable_sha256: sha256(exeBytes) },
    passed: checks.every(item => item.passed), checks, findings,
  };
  await writeFile(args.out, `${JSON.stringify(result, null, 2)}\n`, { flag: 'wx' });
  console.log(`Installer inspection ${result.passed ? 'passed' : 'FAILED'}: ${checks.filter(item => !item.passed).length} failed checks, ${findings.length} findings.`);
  process.exitCode = result.passed ? 0 : 1;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch(error => { console.error(error.message); process.exitCode = 2; });
